-- ───────────────────────────── USUÁRIOS ────────────────────────────────────
-- O login (e-mail e senha) é criado no painel do Supabase (Authentication → Add user).
-- Aqui o ADMIN define nome, login curto, perfil e se está ativo.

create or replace function public.atualizar_usuario(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_login text := lower(public._texto(p, 'login'));
begin
  perform public._exigir_perfil(array['ADMIN']);
  perform public._obrigatorio(p, array['id', 'nome', 'login', 'perfil']);
  if public._texto(p, 'perfil') not in ('ADMIN', 'DIRETOR', 'FINANCEIRO') then
    raise exception 'Perfil inválido: %.', public._texto(p, 'perfil') using errcode = '22023';
  end if;
  if exists (select 1 from public.usuarios where lower(login) = v_login and id <> (p ->> 'id')::uuid) then
    raise exception 'Login "%" já está em uso por outro usuário.', v_login using errcode = '23505';
  end if;
  update public.usuarios set nome = public._texto(p, 'nome'), login = v_login, perfil = public._texto(p, 'perfil')
  where id = (p ->> 'id')::uuid;
  if not found then raise exception 'Usuário não encontrado.' using errcode = 'P0002'; end if;
  return json_build_object('atualizado', true);
end $$;

create or replace function public.toggle_usuario(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
begin
  perform public._exigir_perfil(array['ADMIN']);
  perform public._obrigatorio(p, array['id', 'ativo']);
  if (p ->> 'id')::uuid = auth.uid() and not (p ->> 'ativo')::boolean then
    raise exception 'Você não pode desativar o seu próprio usuário.' using errcode = '42501';
  end if;
  if (p ->> 'ativo')::boolean
     and (select perfil from public.usuarios where id = (p ->> 'id')::uuid) is null then
    raise exception 'Defina o perfil do usuário antes de ativá-lo.' using errcode = '22023';
  end if;
  update public.usuarios set ativo = (p ->> 'ativo')::boolean where id = (p ->> 'id')::uuid;
  if not found then raise exception 'Usuário não encontrado.' using errcode = 'P0002'; end if;
  return json_build_object('ativo', (p ->> 'ativo')::boolean);
end $$;

-- Todo login criado no painel ganha um perfil vazio e inativo, esperando o ADMIN
create or replace function public.novo_usuario_auth() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.usuarios (id, email, nome)
  values (new.id, new.email, split_part(new.email, '@', 1))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists ao_criar_usuario on auth.users;
create trigger ao_criar_usuario
  after insert on auth.users
  for each row execute function public.novo_usuario_auth();

