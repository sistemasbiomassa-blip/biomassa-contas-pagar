-- Tudo o que as telas usam, no mesmo formato que o sistema já espera
create or replace function public.carregar_dados() returns json
language plpgsql stable security definer set search_path = public as $$
begin
  perform public._exigir_perfil(array['ADMIN', 'DIRETOR', 'FINANCEIRO']);
  return json_build_object(
    'contas', coalesce((
      select json_agg(json_build_object(
        'id', c.id::text, 'fornecedor', c.fornecedor, 'categoria', c.categoria,
        'solicitante', c.solicitante, 'descricao', c.descricao, 'valor', c.valor,
        'vencimento', to_char(c.vencimento, 'YYYY-MM-DD'), 'competencia', c.competencia,
        'dataPagamento', coalesce(to_char(c.data_pagamento, 'YYYY-MM-DD'), ''),
        'formaPagamento', c.forma_pagamento, 'jurosMulta', c.juros_multa,
        'numDocumento', c.num_documento, 'observacao', c.observacao,
        'usuario', c.usuario, 'dataRegistro', to_char(c.data_registro, 'YYYY-MM-DD')
      ) order by c.id) from public.contas c), '[]'::json),
    'fornecedores', coalesce((
      select json_agg(json_build_object(
        'id', f.id::text, 'nome', f.nome, 'tipo', f.tipo, 'documento', f.documento,
        'telefone', f.telefone, 'email', f.email, 'categoriaPadrao', f.categoria_padrao,
        'observacao', f.observacao, 'ativo', f.ativo
      ) order by f.id) from public.fornecedores f), '[]'::json),
    'categorias', coalesce((
      select json_agg(json_build_object(
        'id', k.id::text, 'nome', k.nome, 'tipo', k.tipo, 'frota', k.frota,
        'observacao', k.observacao, 'ativo', k.ativo
      ) order by k.id) from public.categorias k), '[]'::json),
    'solicitantes', coalesce((
      select json_agg(json_build_object(
        'id', s.id::text, 'nome', s.nome, 'departamento', s.departamento, 'cargo', s.cargo,
        'email', s.email, 'telefone', s.telefone, 'ativo', s.ativo
      ) order by s.id) from public.solicitantes s), '[]'::json)
  );
end $$;

create or replace function public.listar_usuarios() returns json
language plpgsql stable security definer set search_path = public as $$
begin
  perform public._exigir_perfil(array['ADMIN']);
  return coalesce((
    select json_agg(json_build_object(
      'id', u.id::text, 'nome', u.nome, 'email', u.email,
      'login', coalesce(u.login, ''), 'perfil', coalesce(u.perfil, ''), 'ativo', u.ativo
    ) order by u.nome) from public.usuarios u), '[]'::json);
end $$;

-- ───────────────────────────── CONTAS ──────────────────────────────────────

create or replace function public.criar_conta(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_id    bigint;
  v_chave text := nullif(public._texto(p, 'chaveEnvio'), '');
begin
  perform public._exigir_perfil(array['ADMIN', 'FINANCEIRO']);
  perform public._obrigatorio(p, array['fornecedor', 'categoria', 'descricao', 'valor', 'vencimento']);

  if v_chave is not null then
    select id into v_id from public.contas where chave_envio = v_chave;
    if found then return json_build_object('id', v_id::text, 'repetido', true); end if;
  end if;

  insert into public.contas (fornecedor, categoria, solicitante, descricao, valor, vencimento,
                             competencia, num_documento, observacao, usuario, chave_envio)
  values (public._texto(p, 'fornecedor'), public._texto(p, 'categoria'), public._texto(p, 'solicitante'),
          public._texto(p, 'descricao'), public._numero(p ->> 'valor', 'valor'),
          public._data(p ->> 'vencimento', 'vencimento'), public._competencia(p ->> 'competencia'),
          public._texto(p, 'numDocumento'), public._texto(p, 'observacao'), public.meu_login(), v_chave)
  returning id into v_id;

  return json_build_object('id', v_id::text);
exception when unique_violation then
  -- o mesmo envio chegou duas vezes ao mesmo tempo
  select id into v_id from public.contas where chave_envio = v_chave;
  return json_build_object('id', v_id::text, 'repetido', true);
end $$;

-- Todas as parcelas numa única transação: ou grava todas, ou nenhuma
create or replace function public.criar_conta_parcelada(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_chave  text := nullif(public._texto(p, 'chaveEnvio'), '');
  v_parc   jsonb;
  v_ids    json;
  v_total  int;
begin
  perform public._exigir_perfil(array['ADMIN', 'FINANCEIRO']);
  perform public._obrigatorio(p, array['fornecedor', 'categoria', 'descricao']);

  if jsonb_typeof(p -> 'parcelas') is distinct from 'array' or jsonb_array_length(p -> 'parcelas') < 2 then
    raise exception 'É necessário informar ao menos 2 parcelas.' using errcode = '22023';
  end if;

  for v_parc in select * from jsonb_array_elements(p -> 'parcelas') loop
    if public._numero(v_parc ->> 'valor', 'valor da parcela') <= 0
       or public._data(v_parc ->> 'vencimento', 'vencimento da parcela') is null then
      raise exception 'Cada parcela deve ter valor e vencimento.' using errcode = '22023';
    end if;
  end loop;

  if v_chave is not null and exists (select 1 from public.contas where chave_envio = v_chave || '#1') then
    select json_agg(id::text order by id), count(*) into v_ids, v_total
    from public.contas where starts_with(chave_envio, v_chave || '#');
    return json_build_object('ids', v_ids, 'total', v_total, 'repetido', true);
  end if;

  with inseridas as (
    insert into public.contas (fornecedor, categoria, solicitante, descricao, valor, vencimento,
                               competencia, num_documento, observacao, usuario, chave_envio)
    select public._texto(p, 'fornecedor'), public._texto(p, 'categoria'), public._texto(p, 'solicitante'),
           coalesce(nullif(public._texto(x, 'descricao'), ''), public._texto(p, 'descricao')),
           public._numero(x ->> 'valor', 'valor da parcela'), public._data(x ->> 'vencimento', 'vencimento da parcela'),
           public._competencia(p ->> 'competencia'), public._texto(p, 'numDocumento'),
           public._texto(p, 'observacao'), public.meu_login(),
           case when v_chave is null then null else v_chave || '#' || ord end
    from jsonb_array_elements(p -> 'parcelas') with ordinality as t (x, ord)
    order by ord
    returning id
  )
  select json_agg(id::text order by id), count(*) into v_ids, v_total from inseridas;

  return json_build_object('ids', v_ids, 'total', v_total);
end $$;

create or replace function public.atualizar_conta(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_perfil text;
  v_dono   text;
begin
  v_perfil := public._exigir_perfil(array['ADMIN', 'FINANCEIRO']);
  perform public._obrigatorio(p, array['id', 'fornecedor', 'categoria', 'descricao', 'valor', 'vencimento']);

  select usuario into v_dono from public.contas where id = (p ->> 'id')::bigint;
  if not found then raise exception 'Conta não encontrada.' using errcode = 'P0002'; end if;
  if v_perfil = 'FINANCEIRO' and v_dono is distinct from public.meu_login() then
    raise exception 'Você só pode editar contas lançadas por você.' using errcode = '42501';
  end if;

  -- Pagamento já registrado é preservado: editar a conta não mexe nele
  update public.contas set
    fornecedor    = public._texto(p, 'fornecedor'),
    categoria     = public._texto(p, 'categoria'),
    solicitante   = public._texto(p, 'solicitante'),
    descricao     = public._texto(p, 'descricao'),
    valor         = public._numero(p ->> 'valor', 'valor'),
    vencimento    = public._data(p ->> 'vencimento', 'vencimento'),
    competencia   = public._competencia(p ->> 'competencia'),
    num_documento = public._texto(p, 'numDocumento'),
    observacao    = public._texto(p, 'observacao')
  where id = (p ->> 'id')::bigint;

  return json_build_object('atualizado', true);
end $$;

create or replace function public.excluir_conta(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
begin
  perform public._exigir_perfil(array['ADMIN']);
  perform public._obrigatorio(p, array['id']);
  delete from public.contas where id = (p ->> 'id')::bigint;
  if not found then raise exception 'Conta não encontrada.' using errcode = 'P0002'; end if;
  return json_build_object('excluido', true);
end $$;

create or replace function public.registrar_pagamento(p jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_pago date;
begin
  perform public._exigir_perfil(array['ADMIN', 'FINANCEIRO']);
  perform public._obrigatorio(p, array['id', 'dataPagamento', 'formaPagamento']);

  select data_pagamento into v_pago from public.contas where id = (p ->> 'id')::bigint for update;
  if not found then raise exception 'Conta não encontrada.' using errcode = 'P0002'; end if;
  if v_pago is not null then
    raise exception 'Esta conta já possui pagamento registrado.' using errcode = '23505';
  end if;

  update public.contas set
    data_pagamento  = public._data(p ->> 'dataPagamento', 'data do pagamento'),
    forma_pagamento = public._texto(p, 'formaPagamento'),
    juros_multa     = public._numero(p ->> 'jurosMulta', 'juros/multa')
  where id = (p ->> 'id')::bigint;

  return json_build_object('registrado', true);
end $$;

