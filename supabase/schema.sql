-- ─────────────────────────────── TABELAS ───────────────────────────────────

-- Perfil de cada login (a senha fica no Supabase Auth, nunca aqui)
create table if not exists public.usuarios (
  id         uuid primary key references auth.users (id) on delete cascade,
  email      text not null,
  nome       text not null default '',
  login      text unique,               -- nome curto gravado nas contas (ex.: nathaliabrito)
  perfil     text check (perfil in ('ADMIN', 'DIRETOR', 'FINANCEIRO')),
  ativo      boolean not null default false,  -- novo login só entra depois que um ADMIN ativar
  criado_em  timestamptz not null default now()
);

create table if not exists public.fornecedores (
  id               bigint generated by default as identity primary key,
  nome             text not null,
  tipo             text not null,
  documento        text not null default '',
  telefone         text not null default '',
  email            text not null default '',
  categoria_padrao text not null default '',
  observacao       text not null default '',
  ativo            boolean not null default true
);

create table if not exists public.categorias (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  tipo       text not null,
  frota      boolean not null default false,
  observacao text not null default '',
  ativo      boolean not null default true
);

create table if not exists public.solicitantes (
  id           bigint generated by default as identity primary key,
  nome         text not null,
  departamento text not null default '',
  cargo        text not null default '',
  email        text not null default '',
  telefone     text not null default '',
  ativo        boolean not null default true
);

create table if not exists public.contas (
  id              bigint generated by default as identity primary key,
  fornecedor      text not null,
  categoria       text not null,
  solicitante     text not null default '',
  descricao       text not null,
  valor           numeric(14, 2) not null check (valor >= 0),
  vencimento      date not null,
  competencia     text not null default '',          -- 'AAAA-MM'
  data_pagamento  date,
  forma_pagamento text not null default '',
  juros_multa     numeric(14, 2) not null default 0,
  num_documento   text not null default '',
  observacao      text not null default '',
  usuario         text not null default '',          -- login de quem lançou
  data_registro   date not null default (now() at time zone 'America/Sao_Paulo')::date,
  chave_envio     text unique,                       -- evita lançamento em dobro
  criado_em       timestamptz not null default now()
);

create index if not exists contas_vencimento_idx on public.contas (vencimento);

-- ─────────────────────── PERFIL DE QUEM ESTÁ LOGADO ────────────────────────

-- Perfil do usuário logado, só se estiver ativo (null = sem acesso)
create or replace function public.meu_perfil() returns text
language sql stable security definer set search_path = public as $$
  select perfil from public.usuarios where id = auth.uid() and ativo
$$;

-- Login curto do usuário logado (gravado em contas.usuario)
create or replace function public.meu_login() returns text
language sql stable security definer set search_path = public as $$
  select coalesce(nullif(login, ''), email) from public.usuarios where id = auth.uid()
$$;

-- Dados do próprio usuário (usado logo após o login)
create or replace function public.meu_usuario() returns json
language sql stable security definer set search_path = public as $$
  select json_build_object('id', id::text, 'nome', nome, 'email', email,
                           'login', coalesce(nullif(login, ''), email), 'perfil', perfil, 'ativo', ativo)
  from public.usuarios where id = auth.uid()
$$;

-- ─────────────────────────── FUNÇÕES AUXILIARES ────────────────────────────

create or replace function public._exigir_perfil(permitidos text[]) returns text
language plpgsql stable security definer set search_path = public as $$
declare
  p text := public.meu_perfil();
begin
  if p is null then
    raise exception 'Sessão expirada ou usuário inativo. Faça login novamente.' using errcode = '42501';
  end if;
  if not (p = any (permitidos)) then
    raise exception 'Seu perfil (%) não tem permissão para esta ação.', p using errcode = '42501';
  end if;
  return p;
end $$;

create or replace function public._obrigatorio(p jsonb, campos text[]) returns void
language plpgsql immutable as $$
declare
  faltando text[];
begin
  select array_agg(c) into faltando
  from unnest(campos) as c
  where nullif(trim(coalesce(p ->> c, '')), '') is null;
  if faltando is not null then
    raise exception 'Campos obrigatórios ausentes: %.', array_to_string(faltando, ', ') using errcode = '22023';
  end if;
end $$;

create or replace function public._texto(p jsonb, campo text) returns text
language sql immutable as $$
  select coalesce(trim(p ->> campo), '')
$$;

create or replace function public._numero(v text, campo text) returns numeric
language plpgsql immutable as $$
begin
  if v is null or trim(v) = '' then return 0; end if;
  return round(trim(v)::numeric, 2);
exception when others then
  raise exception 'Valor inválido em "%": %.', campo, v using errcode = '22023';
end $$;

create or replace function public._data(v text, campo text) returns date
language plpgsql immutable as $$
begin
  if v is null or trim(v) = '' then return null; end if;
  if trim(v) !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'formato'; end if;
  return trim(v)::date;
exception when others then
  raise exception 'Data inválida em "%": %.', campo, v using errcode = '22023';
end $$;

-- Competência sempre como 'AAAA-MM' (aceita também 'AAAA-MM-DD')
create or replace function public._competencia(v text) returns text
language sql immutable as $$
  select case when trim(coalesce(v, '')) ~ '^\d{4}-\d{2}' then left(trim(v), 7) else '' end
$$;

