-- Rodar no SQL Editor do projeto (pode rodar de novo sem perder dados).
--
-- Segurança:
--  • Quem não está logado não vê nada (RLS em todas as tabelas).
--  • Usuário logado, ativo e com perfil só LÊ as tabelas diretamente.
--  • Toda gravação passa por uma função que confere o perfil (mesma matriz de
--    permissões do sistema) — ninguém grava direto nas tabelas.
--  • Lançamentos trazem uma "chave de envio": se o mesmo envio chegar duas vezes
--    (clique duplo, conexão que caiu), o segundo não cria registro novo.
